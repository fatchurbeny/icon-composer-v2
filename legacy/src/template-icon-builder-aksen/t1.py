import asyncio, json, zipfile, io
from playwright.async_api import async_playwright
O='/home/claude/tib/build-aksen/out/'
LUC=open('/tmp/claude-0/luc/package/dist/umd/lucide.min.js').read()
TBJ=open('/tmp/claude-0/tab/package/tabler-nodes-outline.json').read()
JSZ=open('/opt/npm-tools/node_modules/jszip/dist/jszip.min.js').read()
SER=open('/home/claude/series-a-pitch/icon-manifest.json').read()
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); ctx=await b.new_context(viewport={'width':1600,'height':960}, accept_downloads=True); pg=await ctx.new_page()
        errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
        async def h(route):
            u=route.request.url
            if 'lucide' in u and 'tags' not in u: await route.fulfill(body=LUC, content_type='application/javascript')
            elif 'jszip' in u: await route.fulfill(body=JSZ, content_type='application/javascript')
            elif 'tabler-nodes' in u: await route.fulfill(body=TBJ, content_type='application/json', headers={'access-control-allow-origin':'*'})
            else: await route.abort()
        await pg.route('**/*', lambda r: h(r) if r.request.url.startswith('http') else r.continue_())
        await pg.goto('file:///home/claude/template-icon-builder-aksen.html'); await pg.wait_for_timeout(1000)
        await pg.click('#loadSample'); await pg.wait_for_timeout(2500)
        print('pv', await pg.evaluate('pv'), await pg.inner_text('#impSum'))
        await pg.click('#goReview'); await pg.wait_for_timeout(800)
        await pg.screenshot(path=O+'r1.png')
        # select session-schedule, click part, set spark
        uid = await pg.evaluate('items.find(i=>i.id==="session-schedule").uid')
        await pg.click(f'[data-sel="{uid}"]'); await pg.wait_for_timeout(300)
        n = await pg.locator('#bOv [data-part]').count(); print('parts', n)
        bx = await pg.locator('#bOv [data-part="0"]').bounding_box()
        await pg.mouse.click(bx['x']+bx['width']/2, bx['y']+bx['height']*0.5); await pg.wait_for_timeout(300)
        print('parts after click', await pg.evaluate('JSON.stringify(curIt().parts)'))
        await pg.click('[data-spark=star4x2]'); await pg.wait_for_timeout(200)
        await pg.click('[data-mstyle=fill]'); await pg.wait_for_timeout(200)
        await pg.click('[data-pt=deco]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=O+'r2.png')
        # classic preview
        await pg.click('[data-pv=A]'); await pg.wait_for_timeout(400); await pg.screenshot(path=O+'r3.png')
        await pg.click('[data-pv=X]'); await pg.wait_for_timeout(400)
        await pg.click('[data-view=export]'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=O+'x1.png')
        async with pg.expect_download() as d: await pg.click('#exGo')
        dl=await d.value; await dl.save_as(O+'pack.zip')
